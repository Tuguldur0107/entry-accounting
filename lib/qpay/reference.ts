export function qpayBankName(code: string | null | undefined): string | null {
  const found = QPAY_BANK_CODES.find((b) => b.code === (code ?? "").trim());
  return found?.name ?? null;
}

/** Банкны НЭРЭЭС кодыг таана (хуучин `bankAccounts` мөрд код байхгүй) — олдохгүй бол null, ЗОХИОХГҮЙ. */
export function guessQpayBankCode(bankName: string | null | undefined): string | null {
  const needle = (bankName ?? "").trim().toLowerCase().replace(/\s+банк$/u, "");
  if (!needle) return null;
  for (const bank of QPAY_BANK_CODES) {
    const base = bank.name.toLowerCase().replace(/\s+банк$/u, "");
    if (base === needle || base.startsWith(needle) || needle.startsWith(base)) return bank.code;
  }
  return null;
}
