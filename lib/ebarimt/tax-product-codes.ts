/** Барааны НӨАТ горимд тохирох албан жагсаалт (standard → хоосон: код шаардахгүй). */
export function taxProductCodesFor(vatMode: "standard" | "exempt" | "zero"): readonly TaxProductCode[] {
  if (vatMode === "exempt") return VAT_FREE_PRODUCT_CODES;
  if (vatMode === "zero") return VAT_ZERO_PRODUCT_CODES;
  return [];
}

/** Код → нэр (аль ч жагсаалтаас); байхгүй бол null. */
export function taxProductCodeName(code: string | null | undefined): string | null {
  const trimmed = code?.trim();
  if (!trimmed) return null;
  return (
    VAT_FREE_PRODUCT_CODES.find((entry) => entry.code === trimmed)?.name ??
    VAT_ZERO_PRODUCT_CODES.find((entry) => entry.code === trimmed)?.name ??
    null
  );
}
