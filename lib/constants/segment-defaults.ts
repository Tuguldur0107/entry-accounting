/** S1/S6 — байгууллагын бүртгэлээс автоматаар бүрдэх сегментүүд. */
export const COMPANY_SEGMENT_IDS = [1, 6] as const;

export function isCompanySegment(segmentId: number): boolean {
  return (COMPANY_SEGMENT_IDS as readonly number[]).includes(segmentId);
}

/**
 * Тухайн сегментийн стандарт утгууд + модулийн default.
 * S1/S6 (компаниас автомат) ба S3 (дансны лавлах) — хоосон.
 */
export function defaultValuesForSegment(
  segmentId: number
): { code: string; name: string; modules: ModuleKey[] }[] {
  if (segmentId === 3 || isCompanySegment(segmentId)) return [];
  const def = SEGMENT_DEFS.find((d) => d.id === segmentId);
  if (!def) return [];
  return (SEGMENT_DEFAULT_VALUES[segmentId] ?? []).map((value) => ({
    ...value,
    modules: def.defaultModules,
  }));
}

/** Стандарт утгатай (товч идэвхтэй байх) сегментүүд. */
export function hasSegmentDefaults(segmentId: number): boolean {
  return isCompanySegment(segmentId) || defaultValuesForSegment(segmentId).length > 0;
}
